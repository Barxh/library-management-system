    private void prepareForm() throws Exception {
        try {
            List<Member> members = controller.Controller.getInstance().getAllMembers();
            MemberTableModel mtm = new MemberTableModel(members);
            jTable1.setModel(mtm);
        } catch (SocketException e) {
            ((MainForm) getParent()).serverStoped();
            throw e;
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            throw e;
        }

    }

    public void updateTable(Member m) {
        List<Member> members = ((MemberTableModel) jTable1.getModel()).getMembers();
        members.set(selectedRow, m);
        jTable1.setModel(new MemberTableModel(members));
    }

    public void serverStoped() {
        this.dispose();
        ((MainForm) getParent()).serverStoped();
    }

