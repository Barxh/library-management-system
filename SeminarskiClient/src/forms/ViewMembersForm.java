    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        String condition = jTextField1.getText();
        try {
            List<Member> members = controller.Controller.getInstance().getMembersByQuery(condition);
            jTable1.setModel(new MemberTableModel(members));
            JOptionPane.showMessageDialog(null, "System has found members for given value.", "Message", JOptionPane.INFORMATION_MESSAGE);
        } catch (SocketException e) {
            dispose();
            ((MainForm) getParent()).serverStoped();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "System can't find members for given value.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(null, "System can't load member.", "Error", JOptionPane.ERROR_MESSAGE);
        } else {
            List<Member> members = ((MemberTableModel) jTable1.getModel()).getMembers();
            Member m = members.get(selectedRow);
            this.selectedRow = selectedRow;
            UpdateMemberForm umf = new UpdateMemberForm(this, true, m);
            umf.setVisible(true);
            

        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(null, "First you must select member from table");
        } else {
            List<Member> members = ((MemberTableModel) jTable1.getModel()).getMembers();
            Member m = members.get(selectedRow);
            try {
                String message = controller.Controller.getInstance().membershipRenewal(m);
                this.selectedRow = selectedRow;
                updateTable(m);
                JOptionPane.showMessageDialog(null, message);
               
            } catch (SocketException e) {
                dispose();
                ((ViewMembersForm) getParent()).serverStoped();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButton2ActionPerformed

