    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        List<ItemReceipt> items = ((ItemReceiptTableModel)jTable1.getModel()).getItemReceipts();
        try {
            String message = controller.Controller.getInstance().addReceipt(new Receipt(0l,items, receiptDate, librarian ));
            JOptionPane.showMessageDialog(null, message);
            dispose();
        } catch(SocketException e){
            dispose();
            ((MainForm)getParent()).serverStoped();
        }catch (Exception e) {
            JOptionPane.showMessageDialog(null, "System can't add receipt.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(null, "Select item you want to remove");
        } else {
            ItemReceiptTableModel model = (ItemReceiptTableModel) jTable1.getModel();
            model.removeItemAt(selectedRow);
            jTable1.setModel(new ItemReceiptTableModel(model.getItemReceipts()));
        }

    }//GEN-LAST:event_jButton3ActionPerformed

