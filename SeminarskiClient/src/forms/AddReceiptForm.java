    public void addItemReceipt(ItemReceipt itemReceipt) throws Exception{
        if(itemReceipt.getPurchasedQuantity() < 1 || itemReceipt.getBook() == null){
            throw new Exception("Quntity must be integer number bigger than 0 and you must select a book!");
        }
        ItemReceiptTableModel model =((ItemReceiptTableModel)jTable1.getModel());
        if(model.getItemReceipts().contains(itemReceipt)){
            throw new Exception("You already added this book to receipt!");
        }
        model.addItemReceipt(itemReceipt);
        jTable1.setModel(new ItemReceiptTableModel(model.getItemReceipts()));
    }

